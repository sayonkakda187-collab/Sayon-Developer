// Bundle every Prisma migration into a TS module the app can execute at runtime.
//
// The Vercel build runs `prisma migrate deploy`, but when that step fails the
// only record of why lives inside a build log. This gives the running site a way
// to apply the same SQL itself and report the outcome over HTTP.
//
// Statements are split HERE, at generation time, by a scanner that respects
// quoting — not at runtime with a naive split(";"), which would break on any
// semicolon inside a string literal.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const DIR = "prisma/migrations";

function splitStatements(sql) {
  const out = [];
  let buf = "";
  let quote = null;
  let lineComment = false;
  let blockComment = false;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];

    // Comments must be skipped, not just quotes. A "--" comment containing a
    // semicolon would otherwise split a statement in half and leave the rest of
    // the sentence as stray SQL — which is exactly what happened with
    // "siteId stays nullable; app code treats null as the default site".
    if (lineComment) {
      buf += c;
      if (c === "\n") lineComment = false;
      continue;
    }
    if (blockComment) {
      buf += c;
      if (c === "/" && sql[i - 1] === "*") blockComment = false;
      continue;
    }

    if (quote) {
      buf += c;
      if (c === quote) {
        if (sql[i + 1] === quote) {
          buf += sql[++i]; // doubled quote is an escaped quote, not a terminator
        } else {
          quote = null;
        }
      }
      continue;
    }

    if (c === "-" && sql[i + 1] === "-") {
      lineComment = true;
      buf += c;
      continue;
    }
    if (c === "/" && sql[i + 1] === "*") {
      blockComment = true;
      buf += c;
      continue;
    }
    if (c === "'" || c === '"') {
      quote = c;
      buf += c;
      continue;
    }
    if (c === ";") {
      const s = buf.trim();
      if (s) out.push(s);
      buf = "";
      continue;
    }
    buf += c;
  }
  const tail = buf.trim();
  if (tail) out.push(tail);
  // Drop fragments that are nothing but comments.
  return out.filter((s) =>
    s.split("\n").some((l) => l.trim() && !l.trim().startsWith("--")),
  );
}

const names = readdirSync(DIR)
  .filter((n) => n !== "migration_lock.toml")
  .sort();

const migrations = names.map((name) => {
  const raw = readFileSync(join(DIR, name, "migration.sql"), "utf8");
  return {
    name,
    // Prisma stores a sha256 of the file, so recording the same value lets a
    // later `migrate deploy` see these as already applied instead of re-running.
    checksum: createHash("sha256").update(raw).digest("hex"),
    statements: splitStatements(raw),
  };
});

mkdirSync("lib/generated", { recursive: true });
writeFileSync(
  "lib/generated/migrations.ts",
  "// GENERATED by scripts/gen-migrations.mjs — do not edit by hand.\n" +
    "// Regenerate after adding a migration: node scripts/gen-migrations.mjs\n" +
    "export type BundledMigration = { name: string; checksum: string; statements: string[] };\n" +
    `export const MIGRATIONS: BundledMigration[] = ${JSON.stringify(migrations, null, 2)};\n`,
);

const statements = migrations.reduce((n, m) => n + m.statements.length, 0);
console.log(`bundled ${migrations.length} migrations, ${statements} statements`);
